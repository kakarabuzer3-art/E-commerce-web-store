CREATE TABLE IF NOT EXISTS sc_products (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  sku VARCHAR(40) NOT NULL,
  name VARCHAR(160) NOT NULL,
  slug VARCHAR(180) NOT NULL,
  category VARCHAR(60) NOT NULL,
  product_type VARCHAR(120) NOT NULL DEFAULT '',
  description TEXT NOT NULL,
  image_path VARCHAR(255) NOT NULL,
  badge VARCHAR(40) NOT NULL DEFAULT '',
  rating DECIMAL(2,1) NOT NULL DEFAULT 4.5,
  price_cents INT UNSIGNED NOT NULL,
  stock_quantity INT UNSIGNED NOT NULL DEFAULT 0,
  active TINYINT(1) NOT NULL DEFAULT 1,
  removed_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_sc_products_sku (sku),
  UNIQUE KEY uq_sc_products_slug (slug),
  KEY idx_sc_products_category_active (category, active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS sc_orders (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  order_number VARCHAR(40) NOT NULL,
  tracking_access_hash CHAR(64) NOT NULL,
  customer_name VARCHAR(120) NOT NULL,
  customer_email VARCHAR(200) NOT NULL,
  customer_phone VARCHAR(30) NOT NULL,
  shipping_address_1 VARCHAR(180) NOT NULL,
  shipping_address_2 VARCHAR(120) NOT NULL DEFAULT '',
  shipping_city VARCHAR(100) NOT NULL,
  shipping_state VARCHAR(50) NOT NULL,
  shipping_postal_code VARCHAR(10) NOT NULL,
  shipping_country CHAR(2) NOT NULL DEFAULT 'US',
  shipping_method ENUM('standard','express') NOT NULL,
  shipping_status ENUM('unfulfilled','processing','packed','shipped','out_for_delivery','delivered','cancelled') NOT NULL DEFAULT 'processing',
  carrier_name VARCHAR(80) NULL,
  tracking_number VARCHAR(100) NULL,
  out_for_delivery_at DATETIME NULL,
  delivered_at DATETIME NULL,
  payment_method ENUM('cash_on_delivery') NOT NULL DEFAULT 'cash_on_delivery',
  payment_status ENUM('pending','paid','refunded') NOT NULL DEFAULT 'pending',
  currency CHAR(3) NOT NULL DEFAULT 'PKR',
  subtotal_cents INT UNSIGNED NOT NULL,
  shipping_cents INT UNSIGNED NOT NULL,
  tax_cents INT UNSIGNED NOT NULL DEFAULT 0,
  total_cents INT UNSIGNED NOT NULL,
  customer_note TEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_sc_orders_number (order_number),
  KEY idx_sc_orders_email (customer_email),
  KEY idx_sc_orders_shipping_status (shipping_status),
  KEY idx_sc_orders_created_at (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS sc_order_items (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  order_id BIGINT UNSIGNED NOT NULL,
  product_id INT UNSIGNED NULL,
  sku VARCHAR(40) NOT NULL,
  product_name VARCHAR(160) NOT NULL,
  quantity SMALLINT UNSIGNED NOT NULL,
  unit_price_cents INT UNSIGNED NOT NULL,
  line_total_cents INT UNSIGNED NOT NULL,
  PRIMARY KEY (id),
  KEY idx_sc_order_items_order (order_id),
  CONSTRAINT fk_sc_order_items_order FOREIGN KEY (order_id) REFERENCES sc_orders(id) ON DELETE CASCADE,
  CONSTRAINT fk_sc_order_items_product FOREIGN KEY (product_id) REFERENCES sc_products(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
